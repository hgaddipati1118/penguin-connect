  const ENTRIES = EMOJI.map(([emoji, name, keywords], rank) => ({
    emoji,
    name,
    rank,
    words: name.split("_"),
    keywords: keywords ? keywords.split(/\s+/) : [],
  }));

  function scoreEntry(entry, query) {
    if (entry.name === query) return 0;
    if (entry.name.startsWith(query)) return 1;
    if (entry.words.some((word) => word.startsWith(query))) return 2;
    if (entry.keywords.some((word) => word === query)) return 3;
    if (entry.keywords.some((word) => word.startsWith(query))) return 4;
    if (entry.name.includes(query)) return 5;
    return -1;
  }

  function searchEmoji(query, limit = 8) {
    const needle = String(query || "").toLowerCase().trim();
    if (!needle) return [];
    return ENTRIES
      .map((entry) => ({ entry, score: scoreEntry(entry, needle) }))
      .filter((item) => item.score >= 0)
      .sort((a, b) => a.score - b.score || a.entry.rank - b.entry.rank)
      .slice(0, limit)
      .map(({ entry }) => ({ emoji: entry.emoji, name: entry.name }));
  }

  // Finds an in-progress ":shortcode" right before the cursor. Requires 2+ characters so
  // times like "10:30" and smileys like ":)" don't open the picker.
  function emojiQueryAt(text, cursor) {
    const before = String(text || "").slice(0, cursor);
    const match = /(^|[\s([{])(:([a-z0-9_+-]{2,}))$/i.exec(before);
    if (!match) return null;
    return {
      start: cursor - match[2].length,
      end: cursor,
      query: match[3].toLowerCase(),
    };
  }

  // Replaces a completed ":shortcode:" (closing colon typed) with its emoji, Slack-style.
  function completedShortcodeAt(text, cursor) {
    const before = String(text || "").slice(0, cursor);
    const match = /(^|[\s([{]):([a-z0-9_+-]+):$/i.exec(before);
    if (!match) return null;
    const name = match[2].toLowerCase();
    const entry = ENTRIES.find((item) => item.name === name);
    if (!entry) return null;
    return { start: cursor - name.length - 2, end: cursor, emoji: entry.emoji };
  }

